import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {stlMeshXML} from '../dist/shared/stl-mesh.js';
import {assignProjectPalette} from '../dist/shared/bambu-palette.js';
import {bambuPlacement, printGuide} from '../dist/shared/plaque-layout.js';

const fflate = createRequire(import.meta.url)('../dist/vendor/fflate.js');
const preset = JSON.parse(readFileSync(new URL('../dist/presets/bambu-p1s-04.json', import.meta.url), 'utf8'));

export function makePlaque3MF(model) {
  const colors = [...new Set(model.parts.map(part => part.color.toUpperCase()))];
  const settings = { ...preset };
  assignProjectPalette(settings, colors);
  // A centered plaque can occupy the P1S preset's usual prime-tower location.
  settings.enable_prime_tower = '0';
  const materials = colors.map(color => `<base name="${color}" displaycolor="${color}FF"/>`).join('');
  const objects = [], components = [], partSettings = [];
  for (const [index, part] of model.parts.entries()) {
    const id = index + 2;
    const {xml, count} = stlMeshXML(part.buffer);
    const label = `${part.name} ${part.color} Z${part.bottom}-${part.top}mm`;
    const material = colors.indexOf(part.color.toUpperCase());
    partSettings.push(`<part id="${id}" subtype="normal_part"><metadata key="name" value="${label}"/><metadata key="extruder" value="${material + 1}"/><mesh_stat face_count="${count}" edges_fixed="0" degenerate_facets="0" facets_removed="0" facets_reversed="0" backwards_edges="0"/></part>`);
    objects.push(`<object id="${id}" name="${label}" type="model" pid="1" pindex="${material}"><mesh>${xml}</mesh></object>`);
    components.push(`<component objectid="${id}"/>`);
  }
  const {x, y} = bambuPlacement(model);
  const modelXML = '<model unit="millimeter" xml:lang="en-US" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02" xmlns:BambuStudio="http://schemas.bambulab.com/package/2021">' +
    '<metadata name="Application">BambuStudio-02.08.02.61</metadata><metadata name="BambuStudio:3mfVersion">1</metadata>' +
    '<metadata name="Description">Generated by CoasterPrint Plaque Maker</metadata><resources>' +
    '<basematerials id="1">' + materials + '</basematerials>' + objects.join('') +
    '<object id="100" type="model" name="Plaque"><components>' + components.join('') +
    '</components></object></resources><build><item objectid="100" transform="1 0 0 0 1 0 0 0 1 ' +
    `${x} ${y} 0"/></build></model>`;
  const modelSettings = '<config><object id="100"><metadata key="name" value="Plaque"/><metadata key="extruder" value="1"/>' +
    partSettings.join('') + '</object><plate><metadata key="plater_id" value="1"/><metadata key="plater_name" value="Plaque"/>' +
    '<model_instance><metadata key="object_id" value="100"/><metadata key="instance_id" value="0"/></model_instance></plate></config>';
  const files = {
    '[Content_Types].xml': '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/><Default Extension="txt" ContentType="text/plain"/><Default Extension="config" ContentType="application/xml"/></Types>',
    '_rels/.rels': '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Target="/3D/3dmodel.model" Id="rel0" Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/></Relationships>',
    '3D/3dmodel.model': modelXML,
    'Metadata/model_settings.config': modelSettings
  };
  const entries = Object.fromEntries(Object.entries(files).map(([name, xml]) =>
    [name, fflate.strToU8('<?xml version="1.0" encoding="UTF-8"?>' + xml)]));
  entries['Metadata/project_settings.config'] = fflate.strToU8(JSON.stringify(settings));
  entries['Metadata/FILAMENT-HEIGHTS.txt'] = fflate.strToU8(printGuide(model));
  return fflate.zipSync(entries, {level: 4});
}
